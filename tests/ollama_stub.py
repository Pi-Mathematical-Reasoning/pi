class OllamaStub:
    def __init__(self):
        self.version = "0.40.13"
        self.tags = json.loads(json.dumps(TAGS))
        self.show = json.loads(json.dumps(SHOW))
        self.ps = json.loads(json.dumps(PS))
        self.chat = json.loads(json.dumps(CHAT))
        self.chat_delay = 0.0
        self.loaded = True  # whether /api/ps lists the model
        # How many more /api/ps answers still list the model after an unload.
        self.unload_lag = 0
        self._lag_left = None
        self.chat_error = None  # (status, message) to answer /api/chat with
        # What to answer for one problem in particular. Keyed by the problem
        # text; a value may set "content", "done_reason", "delay" and "error".
        self.replies = {}
        self.requests = []  # (method, path, body or None)
        self._stopping = threading.Event()
        self._server = ThreadingHTTPServer(("127.0.0.1", 0), self._handler())
        self._server.daemon_threads = True
        # A short poll interval, so stopping the server does not slow every test.
        self._thread = threading.Thread(
            target=self._server.serve_forever, kwargs={"poll_interval": 0.01}, daemon=True
        )

    @property
    def host(self) -> str:
        return f"http://127.0.0.1:{self._server.server_address[1]}"

    def requests_to(self, path):
        return [request for request in self.requests if request[1] == path]

    def _loaded_models(self):
        if self._lag_left is not None:
            if self._lag_left == 0:
                self.loaded = False
                self._lag_left = None
            else:
                self._lag_left -= 1
        return self.ps if self.loaded else {"models": []}

    def start(self):
        self._thread.start()
        return self

    def stop(self):
        self._stopping.set()
        self._server.shutdown()
        self._server.server_close()

    def _handler(self):
        stub = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def do_GET(self):
                stub.requests.append(("GET", self.path, None))
                if self.path == "/api/ps":
                    self._answer(200, stub._loaded_models())
                elif self.path == "/api/tags":
                    self._answer(200, stub.tags)
                else:
                    self._answer(200, {"version": stub.version})

            def do_POST(self):
                length = int(self.headers.get("Content-Length", 0))
                body = json.loads(self.rfile.read(length) or b"null")
                stub.requests.append(("POST", self.path, body))
                if self.path == "/api/show":
                    self._answer(200, stub.show)
                elif self.path == "/api/generate":
                    # Pi only uses this endpoint to unload: keep_alive 0, no prompt.
                    stub._lag_left = stub.unload_lag
                    self._answer(
                        200,
                        {
                            "model": body["model"],
                            "created_at": "2026-11-21T00:59:35.140015Z",
                            "response": "",
                            "done": True,
                            "done_reason": "unload",
                        },
                    )
                elif self.path == "/api/chat":
                    stub.loaded, stub._lag_left = True, None
                    special = stub.replies.get(body["messages"][-1]["content"], {})
                    stub._stopping.wait(special.get("delay", stub.chat_delay))
                    error = special.get("error", stub.chat_error)
                    if error:
                        status, message = error
                        self._answer(status, {"error": message})
                        return
                    reply = json.loads(json.dumps(stub.chat))
                    if "content" in special:
                        reply["message"]["content"] = special["content"]
                    if "done_reason" in special:
                        reply["done_reason"] = special["done_reason"]
                    self._answer(200, reply)

            def _answer(self, status, payload):
                data = json.dumps(payload).encode()
                try:
                    self.send_response(status)
                    self.send_header("Content-Type", "application/json")
                    self.send_header("Content-Length", str(len(data)))
                    self.end_headers()
                    self.wfile.write(data)
                except (BrokenPipeError, ConnectionResetError):
                    pass  # the client gave up waiting, as the timeout tests intend

        return Handler
